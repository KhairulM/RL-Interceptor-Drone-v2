"""Real-world demonstration (F14 RLS seed-200 pursuer): one config per condition + a randomised run order.

Every config is ../config_real.yaml with only its `opponent:` block replaced, so change radios, fences, filter or
logging there and rerun:   python real_demo/make_configs.py        (from scripts/deploy)

Run order: 3 flights per condition in 3 blocks; each block flies every condition once in a random order (fixed seed),
so battery level and time of day are spread evenly over the conditions instead of being measured.
"""
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.join(HERE, '..', 'config_real.yaml')
SEED = 20261125
FLIGHTS_PER_CONDITION = 3

F22_S25 = 'artifacts/thesis_F22_z2/evader'            # own campaign, final evader (stage 25)
F22_S23 = 'artifacts/thesis_F22_z2/evader_stage23'    # own campaign, second-to-last evader
F10 = 'artifacts/thesis_F10_nofix_s0/evader'                # F10 seed 0, final evader (stage 11)
F8B = 'artifacts/thesis_F8b_roncero_s0/evader'              # AMSPBH (Roncero rules), F8b seed 0, final (stage 25)


def policy(artifact, switch_to=None):
    switch = f'{{artifact_dir: {switch_to}, after_s: 3.0}}' if switch_to else 'null'
    return f"""opponent:
  mode: policy
  artifact_dir: {artifact}
  switch: {switch}
"""


APF = """opponent:
  mode: scripted
  scripted:
    type: apf                  # artificial potential field evader (pursuit_evasion_controller.apf_evader_velocity)
    virtual: false
    speed: 2.0                 # m/s, maximum (the training flee heuristic's speed)
    lookahead: 0.5             # s, setpoint lead
    apf_influence: 3.0         # m, repulsion from the pursuer within this distance (start separation: 2 m)
    apf_wall_margin: 1.0       # m, repulsion from the walls within this distance
    apf_wall_gain: 2.0
    apf_vortex_gain: 1.0       # sideways push around the pursuer (escapes the wall stall)
"""

CONDITIONS = [
    # id, file name, description, opponent block
    ('S1', 'S1_switch_f8b_to_f10', 'switching evader: F8b s0 -> F10 after 3 s', policy(F8B, F10)),
    ('S2', 'S2_switch_f10_to_f8b', 'switching evader: F10 -> F8b s0 after 3 s', policy(F10, F8B)),
    ('O25', 'O25_own_stage25', 'own campaign evader, stage 25 (final)', policy(F22_S25)),
    ('O23', 'O23_own_stage23', 'own campaign evader, stage 23', policy(F22_S23)),
    ('A', 'A_amspbh_f8b', 'AMSPBH evader: F8b seed 0, final (stage 25)', policy(F8B)),
    ('P', 'P_apf', 'scripted APF evader', APF),
]


def main():
    base = open(BASE).read()
    start, end = base.index('\nopponent:\n') + 1, base.index('\narena:\n') + 1
    for cid, name, desc, block in CONDITIONS:
        header = (f'# GENERATED by real_demo/make_configs.py from config_real.yaml; do not edit (edit the base and '
                  f'rerun).\n# Condition {cid}: {desc}.\n')
        with open(os.path.join(HERE, name + '.yaml'), 'w') as f:
            f.write(header + base[:start] + block + '\n' + base[end:])

    rng = random.Random(SEED)
    order = []
    for block in range(FLIGHTS_PER_CONDITION):
        ids = [c for c in CONDITIONS]
        rng.shuffle(ids)
        order += [(block + 1, c) for c in ids]
    lines = ['# Real-world demonstration: run order', '',
             f'Generated by `make_configs.py` (seed {SEED}). Pursuer: F14 RLS seed 200 in every flight. From '
             '`scripts/deploy` run `python pursuit_evasion_controller.py --config real_demo/<config>`; each flight '
             'writes `logs/flights/<time>-<pursuer>-vs-<evader>.csv` + `.json`.', '',
             'Fly in this order. If a flight is invalid (e.g. `pursuer_oob`), note it and fly a replacement of the same '
             'condition at the **end** of the list, not straight away (keeps the order random with respect to the '
             'battery).', '',
             '| # | block | condition | config | done / outcome |', '|---|---|---|---|---|']
    for i, (block, (cid, name, desc, _)) in enumerate(order, 1):
        lines.append(f'| {i} | {block} | {cid}: {desc} | `real_demo/{name}.yaml` | |')
    lines += ['', 'Replacements:', '', '| # | condition | config | outcome |', '|---|---|---|---|', '| | | | |']
    open(os.path.join(HERE, 'RUN_ORDER.md'), 'w').write('\n'.join(lines) + '\n')
    print("\n".join(lines[8:8 + len(order) + 1]))


if __name__ == '__main__':
    main()
